import { spawnSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";

const mobileRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const androidDir = join(mobileRoot, "android");
const localPropertiesPath = join(androidDir, "local.properties");

function resolveAndroidSdkPath() {
  const fromEnv =
    process.env.ANDROID_HOME?.trim() ||
    process.env.ANDROID_SDK_ROOT?.trim();
  if (fromEnv && existsSync(fromEnv)) {
    return fromEnv;
  }
  const defaultMac = join(homedir(), "Library", "Android", "sdk");
  if (existsSync(defaultMac)) {
    return defaultMac;
  }
  throw new Error(
    [
      "Android SDK not found.",
      "Install Android Studio, then set ANDROID_HOME or create android/local.properties with sdk.dir=...",
      `Tried: ${fromEnv ?? "(unset)"} and ${defaultMac}`,
    ].join(" "),
  );
}

if (!existsSync(androidDir)) {
  throw new Error(
    "android/ folder missing. Run: npx expo prebuild --platform android",
  );
}

const sdkDir = resolveAndroidSdkPath();
const contents = `## Auto-generated by scripts/ensure-android-local-properties.mjs\nsdk.dir=${sdkDir.replace(/\\/g, "/")}\n`;
writeFileSync(localPropertiesPath, contents, "utf8");
console.log(`Wrote ${localPropertiesPath} (sdk.dir=${sdkDir})`);

const optimizeScript = join(mobileRoot, "scripts", "optimize-android-gradle.mjs");
if (existsSync(optimizeScript)) {
  spawnSync(process.execPath, [optimizeScript], { stdio: "inherit" });
}
